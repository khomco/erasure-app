//! Pins the licence `Feature` catalog: one row per variant, wire name and a
//! one-line meaning, in `docs/generated/entitlements.txt` (drift-tests
//! story 3).
//!
//! Variant names come from `Feature`'s own serde derive (a deserializer that
//! records the `variants` slice handed to `deserialize_enum`), never from a
//! hand list here. Each summary comes from an exhaustive `match`, so a new
//! variant fails to compile until it has one, and then fails the golden until
//! it is regenerated with
//! `UPDATE_GOLDENS=1 cargo test -p wipe-license --test feature_listing`.
//! The summaries are hand-kept restatements of the `Feature` doc comments in
//! `src/entitlement.rs`; nothing checks one against the other, so update them
//! together.
//!
//! This is a catalog, not a tier → feature matrix: what a tier grants is a
//! pricing decision (ROADMAP L-R8 / W3.3 stay open).

use std::path::{Path, PathBuf};

use serde::de::{self, Deserialize, Visitor};
use wipe_license::Feature;

const REGEN: &str = "UPDATE_GOLDENS=1 cargo test -p wipe-license --test feature_listing";
const GOLDEN: &str = "docs/generated/entitlements.txt";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// A deserializer that only captures the variant names a derived enum
/// passes to `deserialize_enum`, then errors.
struct VariantNames<'a>(&'a mut Option<&'static [&'static str]>);

impl<'de> de::Deserializer<'de> for VariantNames<'_> {
    type Error = de::value::Error;

    fn deserialize_any<V: Visitor<'de>>(self, _: V) -> Result<V::Value, Self::Error> {
        Err(de::Error::custom("only enums are captured"))
    }

    fn deserialize_enum<V: Visitor<'de>>(
        self,
        _name: &'static str,
        variants: &'static [&'static str],
        _visitor: V,
    ) -> Result<V::Value, Self::Error> {
        *self.0 = Some(variants);
        Err(de::Error::custom("variant names captured"))
    }

    serde::forward_to_deserialize_any! {
        bool i8 i16 i32 i64 i128 u8 u16 u32 u64 u128 f32 f64 char str string
        bytes byte_buf option unit unit_struct newtype_struct seq tuple
        tuple_struct map struct identifier ignored_any
    }
}

/// Serde names of `T`'s variants, in declaration order.
fn variant_names<'de, T: Deserialize<'de>>() -> &'static [&'static str] {
    let mut captured = None;
    let _ = T::deserialize(VariantNames(&mut captured));
    captured.expect("type deserializes as an enum")
}

/// One line per feature. No wildcard: a new variant fails to compile here
/// until it has a summary.
fn summary(feature: Feature) -> &'static str {
    match feature {
        Feature::EnterpriseMode => "Customer/Contract/WorkOrder/Asset model (CONTEXT §11 v0.2 #4).",
        Feature::HubSync => "Push certs and config to a hub / control plane.",
        Feature::ErpIntegration => "ITAD-ERP REST + webhook integration tier.",
        Feature::PdfCertificates => "PDF/A-3 certificate rendering.",
        Feature::CertAnchoring => "Optional public anchoring of cert hashes (ADR-0005 §6).",
        Feature::OperatorSso => {
            "Operator sign-in through the customer's identity provider (ADR-0011 §4); gates nothing yet."
        }
    }
}

/// Every variant, name and value, each name checked to round-trip.
fn features() -> Vec<(&'static str, Feature)> {
    variant_names::<Feature>()
        .iter()
        .map(|name| {
            let feature: Feature = serde_json::from_value(serde_json::Value::from(*name))
                .unwrap_or_else(|e| panic!("{name} does not deserialize to a Feature: {e}"));
            assert_eq!(
                serde_json::to_value(feature).unwrap(),
                serde_json::Value::from(*name),
                "{name} does not serialize back to itself"
            );
            (*name, feature)
        })
        .collect()
}

fn render(rows: &[(&str, &str)]) -> String {
    let width = rows.iter().map(|(n, _)| n.len()).max().unwrap_or(0);
    let mut out = format!("# Generated by {REGEN} — do not edit.\n");
    for (name, summary) in rows {
        out.push_str(&format!("{name:<width$}  {summary}\n"));
    }
    out
}

fn produced() -> String {
    let rows: Vec<(&str, &str)> = features()
        .into_iter()
        .map(|(name, f)| (name, summary(f)))
        .collect();
    render(&rows)
}

/// Where `expected` and `actual` first differ: 1-based line number, golden
/// line, produced line (`<end of file>` when one side is shorter).
fn first_difference(expected: &str, actual: &str) -> (usize, String, String) {
    let mut exp = expected.split('\n');
    let mut act = actual.split('\n');
    let mut n = 0;
    loop {
        n += 1;
        match (exp.next(), act.next()) {
            (Some(e), Some(a)) if e == a => continue,
            (None, None) => unreachable!("first_difference called on equal text"),
            (e, a) => {
                let show = |s: Option<&str>| s.map_or("<end of file>".into(), |s| format!("{s:?}"));
                return (n, show(e), show(a));
            }
        }
    }
}

/// With `update`, writes `produced` to `path` (creating its directory) and
/// succeeds; otherwise succeeds only when the file already holds it.
fn check_golden(path: &Path, rel: &str, produced: &str, update: bool) -> Result<(), String> {
    if update {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("creating {dir:?}: {e}"))?;
        }
        return std::fs::write(path, produced).map_err(|e| format!("writing {rel}: {e}"));
    }
    let expected = match std::fs::read_to_string(path) {
        Ok(text) => text.replace("\r\n", "\n"),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return Err(format!(
                "{rel} is missing. Generate it with `{REGEN}` and commit it."
            ));
        }
        Err(e) => return Err(format!("reading {rel}: {e}")),
    };
    if expected == produced {
        return Ok(());
    }
    let (line, golden, now) = first_difference(&expected, produced);
    Err(format!(
        "{rel} is out of date: differs at line {line}\n    golden:   {golden}\n    produced: {now}\nIf the change is intended, regenerate with `{REGEN}` and commit {rel}."
    ))
}

#[test]
fn entitlements_golden_matches() {
    let update = std::env::var("UPDATE_GOLDENS").as_deref() == Ok("1");
    if let Err(why) = check_golden(&repo_root().join(GOLDEN), GOLDEN, &produced(), update) {
        panic!("{why}");
    }
}

#[test]
fn variant_names_come_from_the_derive() {
    let names = variant_names::<Feature>();
    assert!(names.contains(&"hub_sync"), "{names:?}");
    assert!(names.contains(&"operator_sso"), "{names:?}");
    // Declaration order, as serde's derive lists them.
    assert_eq!(names.first(), Some(&"enterprise_mode"));
    let rows = features();
    assert_eq!(rows.len(), names.len());
}

// ---- pure-function tests ----

fn scratch_dir() -> PathBuf {
    // The counter keeps parallel tests apart; the clock alone is too coarse.
    static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    std::env::temp_dir().join(format!(
        "feature-listing-{}-{nanos}-{n}",
        std::process::id()
    ))
}

const ROWS: &[(&str, &str)] = &[("hub_sync", "Push."), ("enterprise_mode", "Model.")];

#[test]
fn renders_header_and_aligned_rows_in_order() {
    assert_eq!(
        render(ROWS),
        format!(
            "# Generated by {REGEN} — do not edit.\nhub_sync         Push.\nenterprise_mode  Model.\n"
        )
    );
}

#[test]
fn missing_golden_names_file_and_regen_command() {
    let root = scratch_dir();
    let path = root.join("nested/entitlements.txt");
    let why = check_golden(&path, "x/entitlements.txt", &render(ROWS), false).unwrap_err();
    assert!(why.contains("x/entitlements.txt is missing"), "{why}");
    assert!(why.contains(REGEN), "{why}");
    assert!(!root.exists());
}

#[test]
fn update_creates_dir_then_passes_and_tolerates_crlf() {
    let root = scratch_dir();
    let path = root.join("nested/entitlements.txt");
    let text = render(ROWS);
    check_golden(&path, "e.txt", &text, true).unwrap();
    check_golden(&path, "e.txt", &text, false).unwrap();
    std::fs::write(&path, text.replace('\n', "\r\n")).unwrap();
    check_golden(&path, "e.txt", &text, false).unwrap();
    std::fs::remove_dir_all(&root).unwrap();
}

#[test]
fn added_or_renamed_variant_names_the_first_differing_line() {
    let root = scratch_dir();
    let path = root.join("entitlements.txt");
    check_golden(&path, "e.txt", &render(ROWS), true).unwrap();

    let added = render(&[ROWS[0], ROWS[1], ("new_thing", "New.")]);
    let why = check_golden(&path, "e.txt", &added, false).unwrap_err();
    assert!(why.contains("differs at line 4"), "{why}");
    assert!(why.contains("golden:   \"\""), "{why}");
    assert!(why.contains("new_thing"), "{why}");
    assert!(why.contains(REGEN), "{why}");

    let renamed = render(&[("hub_push", "Push."), ROWS[1]]);
    let why = check_golden(&path, "e.txt", &renamed, false).unwrap_err();
    assert!(why.contains("differs at line 2"), "{why}");
    assert!(why.contains("hub_sync"), "{why}");
    assert!(why.contains("hub_push"), "{why}");
    std::fs::remove_dir_all(&root).unwrap();
}
