//! Pins the station's HTTP API routes and checks the desktop client covers
//! them (drift-tests story 1).
//!
//! 1. `route_golden_matches`: every route from [`wipe_server::api_route_paths`],
//!    with the methods the built router answers on it, rendered into
//!    `docs/generated/http-routes.txt`. Any difference fails; regenerate with
//!    `UPDATE_GOLDENS=1 cargo test -p wipe-server --test route_golden`.
//! 2. `client_calls_match_routes`: every routed `METHOD /path` has a call in
//!    `apps/desktop/src/api/client.ts` (or `ws.ts`, for the live-events
//!    WebSocket), and the client calls nothing the router does not serve.
//!    `UPDATE_GOLDENS=1` does not relax this check.
//!
//! Methods are probed, not parsed from Rust source: a `TRACE` to a routed
//! path is answered 405 with an `Allow` header listing what is routed there.

use std::{collections::BTreeSet, path::PathBuf, sync::Arc};

use axum::{
    body::Body,
    http::{header::ALLOW, Method, Request, StatusCode},
};
use tower::ServiceExt;
use wipe_cert::SigningKey;
use wipe_engine_mock::{MockBackend, MockTiming};
use wipe_server::{api_route_paths, router, AppState};

const REGEN: &str = "UPDATE_GOLDENS=1 cargo test -p wipe-server --test route_golden";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn test_state() -> AppState {
    let backend = Arc::new(MockBackend::with_catalog(
        wipe_engine_mock::default_devices_public(),
        MockTiming::fast(),
    ));
    AppState::new(backend, None, Arc::new(SigningKey::generate()))
}

/// Every routed `(METHOD, path)`, path in axum's `:name` form. `HEAD` is
/// dropped when `GET` is also allowed, since axum adds it to every `GET`.
async fn routed() -> BTreeSet<(String, String)> {
    let app = router(test_state());
    let mut out = BTreeSet::new();
    for path in api_route_paths() {
        let concrete: String = path
            .split('/')
            .map(|seg| {
                if seg.starts_with(':') {
                    "00000000-0000-0000-0000-000000000000"
                } else {
                    seg
                }
            })
            .collect::<Vec<_>>()
            .join("/");
        let req = Request::builder()
            .method(Method::TRACE)
            .uri(&concrete)
            .body(Body::empty())
            .unwrap();
        let resp = app.clone().oneshot(req).await.unwrap();
        assert_eq!(
            resp.status(),
            StatusCode::METHOD_NOT_ALLOWED,
            "TRACE {concrete} (route {path}) should be 405 so its Allow header lists the routed methods"
        );
        let allow = resp
            .headers()
            .get(ALLOW)
            .unwrap_or_else(|| panic!("405 for {path} has no Allow header"))
            .to_str()
            .unwrap()
            .to_owned();
        let methods: Vec<&str> = allow
            .split(',')
            .map(str::trim)
            .filter(|m| !m.is_empty())
            .collect();
        let has_get = methods.contains(&"GET");
        let mut any = false;
        for method in methods {
            if method == "HEAD" && has_get {
                continue;
            }
            out.insert((method.to_owned(), (*path).to_owned()));
            any = true;
        }
        assert!(any, "route {path} answers no method (Allow: {allow:?})");
    }
    out
}

fn render(routes: &BTreeSet<(String, String)>) -> String {
    let mut lines: Vec<String> = routes.iter().map(|(m, p)| format!("{m} {p}")).collect();
    lines.sort();
    let mut s = format!("# Generated by {REGEN} — do not edit.\n");
    for line in lines {
        s.push_str(&line);
        s.push('\n');
    }
    s
}

/// Compares `actual` with the committed golden at `rel` (repo-relative), or
/// rewrites it when `UPDATE_GOLDENS=1`.
fn assert_golden(rel: &str, actual: &str) {
    let update = std::env::var("UPDATE_GOLDENS").as_deref() == Ok("1");
    if let Err(why) = check_golden(&repo_root().join(rel), rel, actual, update) {
        panic!("{why}");
    }
}

/// With `update`, writes `actual` to `path` (creating directories) and
/// succeeds; otherwise succeeds only when the file holds exactly `actual`.
fn check_golden(
    path: &std::path::Path,
    rel: &str,
    actual: &str,
    update: bool,
) -> Result<(), String> {
    if update {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("creating {dir:?}: {e}"))?;
        }
        return std::fs::write(path, actual).map_err(|e| format!("writing {rel}: {e}"));
    }
    let expected = std::fs::read_to_string(path).map_err(|e| {
        format!("golden {rel} is missing or unreadable ({e}); create it with `{REGEN}`")
    })?;
    // A CRLF checkout must not fail on line endings alone.
    let expected = expected.replace("\r\n", "\n");
    if expected == actual {
        return Ok(());
    }
    let exp: BTreeSet<&str> = expected.lines().collect();
    let act: BTreeSet<&str> = actual.lines().collect();
    let missing: Vec<&&str> = exp.difference(&act).collect();
    let added: Vec<&&str> = act.difference(&exp).collect();
    Err(format!(
        "golden {rel} is out of date.\n  in the golden but no longer produced: {missing:?}\n  \
         produced but not in the golden: {added:?}\nIf the change is intended, regenerate with \
         `{REGEN}` and commit the file."
    ))
}

#[tokio::test]
async fn route_golden_matches() {
    let routes = routed().await;
    assert_golden("docs/generated/http-routes.txt", &render(&routes));
}

#[tokio::test]
async fn client_calls_match_routes() {
    let routes: BTreeSet<(String, String)> = routed()
        .await
        .into_iter()
        .map(|(m, p)| (m, normalise(&p)))
        .collect();

    let desktop = repo_root().join("apps/desktop/src/api");
    let mut client = BTreeSet::new();
    for (file, websocket) in [("client.ts", false), ("ws.ts", true)] {
        let src = std::fs::read_to_string(desktop.join(file))
            .unwrap_or_else(|e| panic!("reading {file}: {e}"));
        for (method, path) in api_calls(&src) {
            // ws.ts opens WebSockets, whose upgrade request is a GET.
            let method = if websocket { "GET".to_owned() } else { method };
            client.insert((method, path));
        }
    }

    if let Some(why) = parity_errors(&routes, &client) {
        panic!("{why}");
    }
}

/// `None` when routes and client calls match exactly; otherwise a message
/// naming the extras on each side.
fn parity_errors(
    routes: &BTreeSet<(String, String)>,
    client: &BTreeSet<(String, String)>,
) -> Option<String> {
    let unclient: Vec<String> = routes
        .difference(client)
        .map(|(m, p)| format!("{m} {p}"))
        .collect();
    let unrouted: Vec<String> = client
        .difference(routes)
        .map(|(m, p)| format!("{m} {p}"))
        .collect();
    if unclient.is_empty() && unrouted.is_empty() {
        return None;
    }
    Some(format!(
        "station routes and desktop client calls disagree ({{}} is a path parameter).\n  \
         routed with no call in client.ts/ws.ts: {unclient:?}\n  \
         called by client.ts/ws.ts but not routed: {unrouted:?}"
    ))
}

// --- a minimal TypeScript lexer: enough to find `/api/` literals ----------

#[derive(Debug, PartialEq)]
enum Tok {
    /// A string or template literal; each `${...}` becomes `{}`.
    Str(String),
    Ident(String),
    Punct(char),
}

/// Tokenises `src`, skipping whitespace and `//` / `/* */` comments.
fn lex(src: &str) -> Vec<Tok> {
    let chars: Vec<char> = src.chars().collect();
    let mut i = 0;
    let mut out = Vec::new();
    lex_until(&chars, &mut i, false, &mut out);
    out
}

/// Lexes from `*i` until an unmatched `}` when `in_template` (the end
/// of a template `${...}`), consuming it; otherwise to the end of input.
fn lex_until(chars: &[char], i: &mut usize, in_template: bool, out: &mut Vec<Tok>) {
    let mut braces = 0usize;
    while *i < chars.len() {
        let c = chars[*i];
        let next = chars.get(*i + 1).copied();
        match c {
            _ if c.is_whitespace() => *i += 1,
            '/' if next == Some('/') => {
                while *i < chars.len() && chars[*i] != '\n' {
                    *i += 1;
                }
            }
            '/' if next == Some('*') => {
                *i += 2;
                while *i < chars.len() && !(chars[*i] == '*' && chars.get(*i + 1) == Some(&'/')) {
                    *i += 1;
                }
                *i = (*i + 2).min(chars.len());
            }
            '"' | '\'' => {
                *i += 1;
                let mut s = String::new();
                while *i < chars.len() && chars[*i] != c {
                    if chars[*i] == '\\' {
                        *i += 1;
                    }
                    if let Some(&ch) = chars.get(*i) {
                        s.push(ch);
                    }
                    *i += 1;
                }
                *i += 1;
                out.push(Tok::Str(s));
            }
            '`' => {
                *i += 1;
                let mut s = String::new();
                while *i < chars.len() && chars[*i] != '`' {
                    if chars[*i] == '\\' {
                        *i += 1;
                        if let Some(&ch) = chars.get(*i) {
                            s.push(ch);
                        }
                        *i += 1;
                    } else if chars[*i] == '$' && chars.get(*i + 1) == Some(&'{') {
                        *i += 2;
                        // The expression's own tokens are not part of the literal.
                        lex_until(chars, i, true, &mut Vec::new());
                        s.push_str("{}");
                    } else {
                        s.push(chars[*i]);
                        *i += 1;
                    }
                }
                *i += 1;
                out.push(Tok::Str(s));
            }
            _ if c.is_alphanumeric() || c == '_' || c == '$' => {
                let start = *i;
                while *i < chars.len()
                    && (chars[*i].is_alphanumeric() || chars[*i] == '_' || chars[*i] == '$')
                {
                    *i += 1;
                }
                out.push(Tok::Ident(chars[start..*i].iter().collect()));
            }
            _ => {
                *i += 1;
                if in_template {
                    if c == '{' {
                        braces += 1;
                    } else if c == '}' {
                        if braces == 0 {
                            return;
                        }
                        braces -= 1;
                    }
                }
                out.push(Tok::Punct(c));
            }
        }
    }
}

/// Drops any `?query` or `#fragment`, then maps `:name` / `*name` (axum)
/// and `{}` (a template `${...}`) segments to `{}`.
fn normalise(path: &str) -> String {
    let path = path.split(['?', '#']).next().unwrap_or(path);
    path.split('/')
        .map(|seg| {
            if seg.starts_with(':') || seg.starts_with('*') || seg.contains("{}") {
                "{}"
            } else {
                seg
            }
        })
        .collect::<Vec<_>>()
        .join("/")
}

/// Every `(METHOD, normalised path)` the source calls: each literal holding
/// `/api/`, with the method from a `method: "X"` in the same call (`GET` when
/// there is none).
fn api_calls(src: &str) -> Vec<(String, String)> {
    let toks = lex(src);
    let mut out = Vec::new();
    for (idx, tok) in toks.iter().enumerate() {
        let Tok::Str(s) = tok else { continue };
        let Some(at) = s.find("/api/") else { continue };
        let path = normalise(&s[at..]);
        out.push((call_method(&toks[idx + 1..]), path));
    }
    out
}

/// Scans the rest of the call after its path literal for `method: "X"` in
/// the options object, stopping at the call's closing `)` or a `;`.
fn call_method(rest: &[Tok]) -> String {
    let mut depth = 0usize;
    for (j, tok) in rest.iter().enumerate() {
        match tok {
            Tok::Punct('(' | '{' | '[') => depth += 1,
            Tok::Punct(')' | '}' | ']') => {
                if depth == 0 {
                    break;
                }
                depth -= 1;
            }
            Tok::Punct(';') if depth == 0 => break,
            Tok::Ident(id) if id == "method" && depth == 1 => {
                if let (Some(Tok::Punct(':')), Some(Tok::Str(m))) =
                    (rest.get(j + 1), rest.get(j + 2))
                {
                    return m.to_uppercase();
                }
            }
            _ => {}
        }
    }
    "GET".to_owned()
}

#[test]
fn lexer_normalises_params_both_ways() {
    let ts = r#"
        a: (id: string) => jsonFetch<X>(`/api/jobs/${id}/start`, { method: "POST" }),
        b: (id: string) => jsonFetch<X>(`/api/devices/${encodeURIComponent(id)}/capabilities`),
        c: (id: string) => jsonFetch<{ s: string }>(
          `/api/manifests/${id}/completion/statement`,
          { method: "POST", body: JSON.stringify({ x: `${id}` }) },
        ),
    "#;
    assert_eq!(
        api_calls(ts),
        vec![
            ("POST".into(), "/api/jobs/{}/start".into()),
            ("GET".into(), "/api/devices/{}/capabilities".into()),
            (
                "POST".into(),
                "/api/manifests/{}/completion/statement".into()
            ),
        ]
    );
    assert_eq!(normalise("/api/jobs/:id/start"), "/api/jobs/{}/start");
    assert_eq!(normalise("/api/files/*rest"), "/api/files/{}");
    assert_eq!(normalise("/api/jobs#top"), "/api/jobs");
    assert_eq!(
        api_calls("q: (s: string) => jsonFetch<X>(`/api/jobs?state=${s}`),"),
        vec![("GET".into(), "/api/jobs".into())]
    );
}

#[test]
fn lexer_ignores_comments() {
    let ts = r#"
        // jsonFetch("/api/line-comment", { method: "DELETE" })
        /* jsonFetch("/api/block-comment") */
        const url = "http://x//not-a-comment"; // "/api/trailing"
        x: () => jsonFetch<Y>("/api/real", { method: "PUT" /* "/api/inline" */ }),
    "#;
    assert_eq!(api_calls(ts), vec![("PUT".into(), "/api/real".into())]);
}

#[test]
fn lexer_reads_websocket_url() {
    let ts = r#"
        function buildWsUrl(): string {
          const proto = window.location.protocol === "https:" ? "wss:" : "ws:";
          return `${proto}//${window.location.host}/api/events`;
        }
    "#;
    assert_eq!(api_calls(ts), vec![("GET".into(), "/api/events".into())]);
}

fn set(items: &[(&str, &str)]) -> BTreeSet<(String, String)> {
    items
        .iter()
        .map(|(m, p)| ((*m).to_owned(), (*p).to_owned()))
        .collect()
}

fn scratch_dir() -> PathBuf {
    std::env::temp_dir().join(format!("route-golden-{}", uuid::Uuid::new_v4()))
}

#[test]
fn golden_fails_on_deleted_or_added_route_and_names_it() {
    let dir = scratch_dir();
    let path = dir.join("routes.txt");
    let golden = render(&set(&[
        ("GET", "/api/health"),
        ("POST", "/api/bay-topology/resolve"),
    ]));
    check_golden(&path, "routes.txt", &golden, true).unwrap();

    // A `.route(...)` line deleted.
    let deleted = render(&set(&[("GET", "/api/health")]));
    let why = check_golden(&path, "routes.txt", &deleted, false).unwrap_err();
    assert!(why.contains("POST /api/bay-topology/resolve"), "{why}");
    assert!(why.contains(REGEN), "{why}");

    // A method chained onto an existing path.
    let added = render(&set(&[
        ("GET", "/api/health"),
        ("POST", "/api/health"),
        ("POST", "/api/bay-topology/resolve"),
    ]));
    let why = check_golden(&path, "routes.txt", &added, false).unwrap_err();
    assert!(why.contains("POST /api/health"), "{why}");
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn golden_regenerates_into_missing_dirs_then_passes() {
    let dir = scratch_dir();
    let path = dir.join("nested/generated/routes.txt");
    let golden = render(&set(&[("GET", "/api/health")]));

    let why = check_golden(&path, "routes.txt", &golden, false).unwrap_err();
    assert!(why.contains("missing") && why.contains(REGEN), "{why}");

    check_golden(&path, "routes.txt", &golden, true).unwrap();
    check_golden(&path, "routes.txt", &golden, false).unwrap();

    // A CRLF checkout of the same golden still passes.
    std::fs::write(&path, golden.replace('\n', "\r\n")).unwrap();
    check_golden(&path, "routes.txt", &golden, false).unwrap();
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn parity_names_uncalled_routes_and_unrouted_calls() {
    let routes = set(&[("GET", "/api/health"), ("POST", "/api/jobs/{}/start")]);
    assert_eq!(parity_errors(&routes, &routes.clone()), None);

    // A new route with no client function.
    let mut more = routes.clone();
    more.insert(("GET".into(), "/api/new-thing".into()));
    let why = parity_errors(&more, &routes).unwrap();
    assert!(why.contains("GET /api/new-thing"), "{why}");

    // A client call to an unrouted path.
    let mut client = routes.clone();
    client.insert(("DELETE".into(), "/api/jobs/{}".into()));
    let why = parity_errors(&routes, &client).unwrap();
    assert!(why.contains("DELETE /api/jobs/{}"), "{why}");
}
